/**
 * The visual baseline is only comparable inside its pinned image.
 *
 * `scripts/portal-web-visual.sh` runs the screenshot specs in
 * `mcr.microsoft.com/playwright:v1.62.1-noble` because rendering is font- and
 * rasteriser-sensitive: the same page drawn on a developer host differs from
 * the recorded PNG by a ratio of 0.01–0.05, well over the 0.002 tolerance.
 *
 * Run bare on a host, the suite therefore reports dozens of mismatches that
 * look like product regressions and are not. That happened twice: the P23
 * contributor run (33 cells, filed as `S06-VISUAL-BASELINE-HOST-DRIFT`
 * awaiting an owner decision) and again on 2026-09-26 (28 cells). In the
 * pinned image the same tree is 332 passed · 16 skipped · 0 failed.
 *
 * So the specs refuse to run outside the image rather than produce a
 * misleading diff. This is a guard, not a policy: nothing here relaxes a
 * comparison, and baselines are still only ever regenerated by the owner.
 */
export function assertPinnedVisualHost(): void {
  if (process.env.PORTAL_VISUAL_PINNED_IMAGE) return;
  throw new Error(
    [
      "Visual baseline specs must run inside the pinned Playwright image.",
      "Run: ./scripts/portal-web-visual.sh   (from the repository root)",
      "A bare `npx playwright test` on a developer host mismatches dozens of",
      "cells because of font and rasteriser differences, not because of a",
      "product change.",
    ].join("\n"),
  );
}
