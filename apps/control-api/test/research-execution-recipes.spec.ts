import {createHash} from "node:crypto";
import {describe,it,expect} from "vitest";
import {EXECUTION_RECIPE_TABLE} from "../src/research/execution-recipes.generated";
import {executionRecipes,executionRecipe,executionRecipeActivationReason,executionRecipeBudgets,executionRecipeResources,
  executionRecipeTrialCount,assertExecutionRecipeTable,recipeDigest,EXECUTION_RECIPE_REVISION,wfoExecutionRecipe} from "../src/research/execution-recipes";
import {researchPortalAdmission} from "../src/research/portal-admission";
import {VN_OBSERVED_FIXED_PROFILE as vn,VN_OBSERVED_FIXED_PROFILE_DIGEST} from "../src/research/vn-observed-fixed.profile";

describe("FULL-01 exact historical recipe authority",()=>{
  it("keeps all six profile IDs/digests and independently hashes each old descriptor",()=>{
    expect(executionRecipes.slice(0,6).map(r=>r.profile_digest)).toEqual([null,
      "b86c66fa68c41e76c6106bd06a48b5ba1281bc4b168a915ec2fa7e34ec2a6cca",
      "d65291f776dce1fef162da9eb6505ba63fc6e3ae0f55679fe12dece3858c7fa0",
      "60a041b373808405f8896aee0a3421d41cc2199d516dadc9f40e1187e2fefdd1",
      "acb6566ebae23bcf77c77974136c9d083a95f0967260b1332530f600f5abe00e",
      "f1ed5dbccdd90ca7dd35be2755f3b3b5f7e9a29b1641beb08bd0136783c0f298"]);
    executionRecipes.forEach(r=>{if(r.profile_digest)expect(recipeDigest(r.descriptor)).toBe(r.profile_digest);});
    expect(executionRecipe("p04.fixed-qualification.v1",null).profile_digest).toBeNull();
    expect(()=>executionRecipe("unknown")).toThrow();
    expect(()=>executionRecipe("p10.delta-signal-notional-wfo.v1","0".repeat(64))).toThrow();
    expect(()=>executionRecipe("p10.delta-signal-notional-wfo.v1",null)).toThrow();
    expect(()=>executionRecipe("p04.fixed-qualification.v1","0".repeat(64))).toThrow();
  });
  it("refuses tampered generated bytes/policies and duplicate bindings before admission",()=>{
    const changed=structuredClone(EXECUTION_RECIPE_TABLE);
    (changed.recipes[0].budgets as {cpu_seconds:number}).cpu_seconds=46;
    expect(()=>assertExecutionRecipeTable(changed,EXECUTION_RECIPE_REVISION)).toThrow("revision mismatch");
    expect(()=>assertExecutionRecipeTable(changed,recipeDigest(changed))).toThrow("qualification/profile mismatch");
    const duplicate=structuredClone(EXECUTION_RECIPE_TABLE);
    (duplicate.recipes as unknown[]).push(duplicate.recipes[0]);
    expect(()=>assertExecutionRecipeTable(duplicate,recipeDigest(duplicate))).toThrow("Ambiguous");
    expect(Object.isFrozen(executionRecipes[1].descriptor.child_limits)).toBe(true);
  });
  it("isolates the preview global budget and keeps causal/default queue costs exact",()=>{
    const global=executionRecipe("p10.delta-signal-notional-wfo.v2"),causal=executionRecipe("p10.delta-signal-notional-causal-inner.v1");
    const preview={FEATURE_RESEARCH_PREVIEW_LONG_WFO:"true",PORTAL_ENV:"local",AUTH_MODE:"dev"};
    expect(executionRecipeBudgets(global,{})).toMatchObject({cpu_seconds:120,wall_seconds:240});
    expect(executionRecipeBudgets(global,preview)).toMatchObject({cpu_seconds:1800,wall_seconds:3600});
    expect(executionRecipeTrialCount(global,preview)).toEqual({min:2,max:400});
    expect(executionRecipeBudgets(causal,preview)).toMatchObject({cpu_seconds:120,wall_seconds:240});
    expect(executionRecipeTrialCount(causal,preview)).toEqual({min:3,max:3});
    expect(()=>executionRecipeBudgets(global,{...preview,PORTAL_ENV:"production"})).toThrow();
    expect(()=>executionRecipeBudgets(global,{...preview,AUTH_MODE:"cookie"})).toThrow();
    expect(executionRecipeResources(causal,preview)).toEqual({memoryBytes:4294967296,cpuSeconds:120,scratchBytes:134217728,ioBytes:536870912});
  });
  it("keeps exact historical requested-spec/schedule family selection",()=>{
    expect(wfoExecutionRecipe({schema_version:"research.requested-spec.v1",optimization_schedule:"global"})?.profile_id).toBe("p10.delta-signal-notional-wfo.v1");
    expect(wfoExecutionRecipe({schema_version:"research.requested-spec.v2",optimization_schedule:"per_fold_causal"})?.profile_id).toBe("p10.delta-signal-notional-causal-inner.v1");
    expect(wfoExecutionRecipe({schema_version:"research.requested-spec.v1",optimization_schedule:"per_fold_causal"})).toBeNull();
    expect(wfoExecutionRecipe({schema_version:"research.requested-spec.v2",optimization_schedule:"per_fold_decay"})?.profile_id).toBe("p10.delta-signal-notional-per-fold-decay.v1");
    expect(executionRecipeActivationReason(executionRecipe(vn.profile_id),{FEATURE_RESEARCH_RUN_PRODUCER:"true",FEATURE_RESEARCH_VN_OBSERVED_PROFILE:"true"},
      {engine_release_id:"er_quantbt_111",verified:true,context_qualified:false})).toBe("SOURCE_PROFILE_UNQUALIFIED");
  });
  it("matches 192 old Atlas admission results independently captured from git baseline 491eb066",()=>{
    const q={state:"AVAILABLE",reason_code:null,profile_id:vn.profile_id,profile_digest:VN_OBSERVED_FIXED_PROFILE_DIGEST,
      dataset_id:vn.dataset_id,symbol:vn.symbol,timeframe:vn.timeframe,source_timezone:vn.source_timezone,
      clock_basis:vn.clock_basis,index_revision:"a".repeat(64)};
    const results=[];
    for(const release_id of ["er_quantbt_111","er_quantbt_110","er_quantbt_112"])for(const verified of [false,true])
    for(const qualification of [null,q])for(let bits=0;bits<16;bits++){
      const flags={FEATURE_RESEARCH_RUN_PRODUCER:bits&1?"true":"false",FEATURE_RESEARCH_WFO_PROFILE:bits&2?"true":"false",
        FEATURE_RESEARCH_PREVIEW_LONG_WFO:bits&4?"true":"false",FEATURE_RESEARCH_VN_OBSERVED_PROFILE:bits&8?"true":"false"};
      results.push(researchPortalAdmission(flags as never,{release_id,verified,vn_observed_daily_qualification:qualification} as never));
    }
    expect(results).toHaveLength(192);
    expect(recipeDigest(results)).toBe("3c0dd1fa932ecbb773ead7f8632624451c7a13b973319c8bcf79797b2fb5bacc");
    // Atlas ETags hash the wire JSON, so semantic equality alone misses key-order drift.
    expect(createHash("sha256").update(JSON.stringify(results)).digest("hex"))
      .toBe("3ec4a92d48d0acb80dc9c71530a580a5c024235b2cd0c2628d7a946daa63dec6");
  });
});
