/** Synthetic schema/derivation units, not a new engine or preview receipt. */
import { readFileSync } from "node:fs";
import { resolve } from "node:path";
import { describe, expect, it } from "vitest";
import { ReplayBoundaryFactSchema, ReplaySplitShapeSchema, ReplayWindowCursorSchema } from "../src/research/replay-continuity.contract";
import { replayBoundaryFacts, replaySplitShape, replayWindowCursor } from "../src/research/replay-continuity";
import { ResearchCurrentSourcePageQuerySchema, ResearchCurrentSourceReplayQuerySchema } from "../src/research/current-source.contract";
import { openApiValidator } from "./research-rf05-openapi";
const fixtureDir = resolve(process.env.PORTAL_CONTRACTS_DIR ?? resolve(__dirname, "../../../packages/contracts"), "fixtures");
const fixture = (name: string) => JSON.parse(readFileSync(resolve(fixtureDir, `research-replay-continuity.${name}.synthetic.valid.json`), "utf8"));
const multi = fixture("multifold"), mode5 = fixture("mode5");
const segments = multi.split_shape.windows.map((w: any, i: number) => ({
  ...w, start_basis: "PREVIOUS_OBSERVATION" as const, end_equity: "20123.456789012345", end_position: "-0.03123",
  params_digest: (i ? "b" : "a").repeat(64), selected_trial_id: i ? "study_1.trial_1" : "study_0.trial_2", study_id: String(i),
}));
const global = { trialId: null, studyId: null, synthetic: false };

describe("CG-RP-01/03/05 served replay semantics", () => {
  it("one full window requires exact Mode5 identity plus retained disclosure, never fold count alone", () => {
    const single = [{ ...segments[0], fold_id: "full", first_ordinal: 0, last_ordinal: 31, bars: 32 }];
    expect(replaySplitShape("FULL_SAMPLE", single, 32, true)).toEqual(mode5);
    expect(replaySplitShape("THREE_WINDOW", single, 32, false)).toMatchObject({ window_kind: "FOLD_WINDOWS", oos_applicable: true, independent_holdout: true });
    expect(() => replaySplitShape("FULL_SAMPLE", single, 32, false)).toThrow();
    expect(() => replaySplitShape("FULL_SAMPLE", segments, 336, true)).toThrow();
    expect(replaySplitShape("GLOBAL_WFO", [], 336, false)).toMatchObject({ state: "NOT_PUBLISHED", window_kind: null, oos_applicable: null });
  });
  it("canonical multifold fixture is generated by the same reader derivation", () => {
    expect(replaySplitShape("PER_FOLD_DECAY", segments, 336, false)).toEqual(multi.split_shape);
    expect(replayBoundaryFacts(segments, "carry_position", global)).toEqual(multi.boundaries);
    expect(replayWindowCursor(segments, [{ sourceOrdinal: 100 }, { sourceOrdinal: 200 }], multi.page)).toEqual(multi.window_cursor);
    ReplaySplitShapeSchema.parse(multi.split_shape); ReplaySplitShapeSchema.parse(mode5);
    ReplayBoundaryFactSchema.parse(multi.boundaries[0]); ReplayWindowCursorSchema.parse(multi.window_cursor);
    for (const [name, value] of [["ReplaySplitShape", mode5], ["ReplaySplitShape", multi.split_shape],
      ["ReplayBoundaryFact", multi.boundaries[0]], ["ReplayWindowCursor", multi.window_cursor], ["ReplayPage", multi.page]] as const)
      openApiValidator("research-current-source.openapi.json", name).assert(value);
  });
  it("rejects overlap, duplicate fold IDs, wrong bar counts and Mode5 OOS claims", () => {
    const overlap = structuredClone(segments); overlap[1].first_ordinal = 100;
    expect(() => replaySplitShape("GLOBAL_WFO", overlap, 336, false)).toThrow();
    for (const value of [{ ...mode5, oos_applicable: true }, { ...mode5, independent_holdout: true },
      { ...mode5, windows: [...mode5.windows, ...mode5.windows] }, { ...mode5, injected: true }]) {
      expect(ReplaySplitShapeSchema.safeParse(value).success).toBe(false);
      expect(openApiValidator("research-current-source.openapi.json", "ReplaySplitShape").check(value)).toBe(false);
    }
    const bad = structuredClone(multi.split_shape); bad.windows[1].fold_id = bad.windows[0].fold_id;
    expect(ReplaySplitShapeSchema.safeParse(bad).success).toBe(false);
    bad.windows[1].fold_id = "other"; bad.windows[1].bars = 1;
    expect(ReplaySplitShapeSchema.safeParse(bad).success).toBe(false);
  });
  it("distinguishes carry, reset, boundary close, and unknown policy without changing financial bytes", () => {
    for (const [policy, equity, position] of [["carry_position", "CARRIED", "CARRIED"],
      ["close_at_boundary", "CARRIED", "CLOSED_AT_BOUNDARY"], ["reset_flat", "RESET", "RESET_FLAT"],
      [null, "NOT_ASSERTED", "NOT_ASSERTED"]] as const) {
      const [fact] = replayBoundaryFacts(segments, policy, global);
      ReplayBoundaryFactSchema.parse(fact);
      expect(fact).toMatchObject({ equity_start_policy: equity, position_start_policy: position,
        previous_end_equity: "20123.456789012345", previous_end_position: "-0.03123" });
    }
    const same = segments.map((s: any) => ({ ...s, params_digest: "a".repeat(64) }));
    expect(replayBoundaryFacts(same, "carry_position", global)[0]!.params_digest_changed).toBe(false);
    const missing = segments.map((s: any) => ({ ...s, params_digest: null, study_id: undefined, selected_trial_id: undefined }));
    const [fact] = replayBoundaryFacts(missing, null, { ...global, synthetic: true });
    expect(fact).toMatchObject({ params_digest_changed: null, params_digest_reason_code: "RS02_SEAL_DID_NOT_RETAIN_SELECTED_PARAMETERS",
      selection: { selected_trial_id: null, selected_trial_reason_code: "SYNTHETIC_SELECTION_HAS_NO_TRIAL", study_id: null } });
    ReplayBoundaryFactSchema.parse(fact);
    expect(ReplayBoundaryFactSchema.safeParse({ ...multi.boundaries[0], params_digest_changed: false }).success).toBe(false);
  });
  it("crossing is explicit for the incoming edge, in both directions; legacy remains unknown", () => {
    const page = { next_cursor: null, prev_cursor: null };
    expect(replayWindowCursor(segments, [{ sourceOrdinal: 168 }], page, { ordinal: 167, direction: "after" }))
      .toMatchObject({ crossed_fold_boundary: true, first_fold_id: "outer_1" });
    expect(replayWindowCursor(segments, [{ sourceOrdinal: 167 }], page, { ordinal: 168, direction: "before" }))
      .toMatchObject({ crossed_fold_boundary: true, last_fold_id: "outer_0" });
    const absent = replayWindowCursor([], [{ sourceOrdinal: 0 }], page);
    expect(absent).toMatchObject({ state: "NOT_PUBLISHED", crossed_fold_boundary: null });
    ReplayWindowCursorSchema.parse(absent);
  });
  it("raises only Replay to 400; other relation pages and unscoped selector inputs remain rejected", () => {
    expect(ResearchCurrentSourceReplayQuerySchema.parse({ limit: 400 }).limit).toBe(400);
    expect(ResearchCurrentSourcePageQuerySchema.safeParse({ limit: 201 }).success).toBe(false);
    for (const query of [{ limit: 401 }, { limit: 0 }, { limit: 1.5 }, { fold_id: "0" }, { at_ordinal: 0 }])
      expect(ResearchCurrentSourceReplayQuerySchema.safeParse(query).success).toBe(false);
  });
});
