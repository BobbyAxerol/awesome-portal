#!/usr/bin/env node
/**
 * EDS-02 source compiler.
 *
 * The E3 return-pack is immutable input evidence.  Control API must not read
 * it at runtime, so this deterministic compiler turns the non-secret, pinned
 * coverage metadata into a checked-in TypeScript module.  The module contains
 * no source credentials, network addresses or direct-query handles.
 */
import { createHash } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const toolingDirectory = dirname(fileURLToPath(import.meta.url));
const repositoryRoot = resolve(toolingDirectory, "../../..");
const sourcePack = process.env.EDS02_SOURCE_PACK ?? join(
  repositoryRoot,
  "services/portal-execution-edge-rs/contracts/maximum-data-return-v1",
);
const outputFile = process.env.EDS02_GENERATED_OUTPUT ?? join(
  toolingDirectory,
  "../src/execution/eds02-contract-source.generated.ts",
);
const checkOnly = process.argv.includes("--check");

function sha256(value) {
  return `sha256:${createHash("sha256").update(value).digest("hex")}`;
}

function read(name) {
  const absolute = join(sourcePack, name);
  return { absolute, body: readFileSync(absolute, "utf8") };
}

/** Small RFC-4180 parser: the E3 CSVs intentionally use a stable header. */
function parseCsv(body, name) {
  const rows = [];
  let row = [];
  let value = "";
  let quoted = false;
  for (let index = 0; index < body.length; index += 1) {
    const character = body[index];
    if (quoted) {
      if (character === '"' && body[index + 1] === '"') {
        value += '"';
        index += 1;
      } else if (character === '"') {
        quoted = false;
      } else {
        value += character;
      }
      continue;
    }
    if (character === '"') {
      quoted = true;
    } else if (character === ",") {
      row.push(value);
      value = "";
    } else if (character === "\n") {
      row.push(value.replace(/\r$/, ""));
      rows.push(row);
      row = [];
      value = "";
    } else {
      value += character;
    }
  }
  if (quoted) throw new Error(`${name}: unterminated quoted CSV value`);
  if (value.length > 0 || row.length > 0) {
    row.push(value.replace(/\r$/, ""));
    rows.push(row);
  }
  const [header, ...records] = rows.filter((candidate) => candidate.some((cell) => cell.length > 0));
  if (!header || header.length === 0) throw new Error(`${name}: missing CSV header`);
  return records.map((cells, lineOffset) => {
    if (cells.length !== header.length) {
      throw new Error(`${name}: line ${lineOffset + 2} has ${cells.length} cells; expected ${header.length}`);
    }
    return Object.fromEntries(header.map((key, index) => [key, cells[index]]));
  });
}

function readJson(name) {
  const file = read(name);
  return { body: JSON.parse(file.body), digest: sha256(file.body) };
}

const inputs = {
  fieldDefinitions: readJson("e3-field-definitions.v1.json"),
  screenInventory: readJson("e3-screen-inventory.v1.json"),
  ownerResponse: readJson("owner-response.v2.json"),
  existingPublication: readJson("e5-existing-data-publication.v1.json"),
  screenCoverage: read("SCREEN_FIELD_SOURCE_COVERAGE.csv"),
  actionCoverage: read("ACTION_CAPABILITY_COVERAGE.csv"),
};

const generatedSource = {
  schema_version: "portal.execution.eds02.generated-source.v1",
  source_pack: "maximum-data-return-v1",
  input_digests: Object.fromEntries(
    Object.entries(inputs).map(([name, input]) => [
      name,
      "digest" in input ? input.digest : sha256(input.body),
    ]),
  ),
  field_definitions: inputs.fieldDefinitions.body.fields,
  screen_inventory: inputs.screenInventory.body.screens,
  screen_field_coverage: parseCsv(inputs.screenCoverage.body, "SCREEN_FIELD_SOURCE_COVERAGE.csv"),
  action_capability_coverage: parseCsv(inputs.actionCoverage.body, "ACTION_CAPABILITY_COVERAGE.csv"),
  owner_capabilities: inputs.ownerResponse.body.capabilities,
  e5_publication_entries: inputs.existingPublication.body.entries,
  page_bounds: inputs.existingPublication.body.page_bounds,
};

const rendered = [
  "/* This file is generated by tooling/generate-eds02-contract-source.mjs. Do not edit manually. */",
  "/* Source: maximum-data-return-v1 E3/E5 owner evidence; no secret or raw source access handle is emitted. */",
  `export const EDS02_GENERATED_SOURCE = ${JSON.stringify(generatedSource, null, 2)} as const;`,
  "",
].join("\n");

if (checkOnly) {
  if (!existsSync(outputFile) || readFileSync(outputFile, "utf8") !== rendered) {
    throw new Error(`EDS-02 generated source drift: ${outputFile}`);
  }
  process.stdout.write(`EDS-02 generated source verified: ${outputFile}\n`);
} else {
  writeFileSync(outputFile, rendered, "utf8");
  process.stdout.write(`EDS-02 generated source written: ${outputFile}\n`);
}
