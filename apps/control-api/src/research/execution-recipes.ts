/** Historical lookup ignores activation, but requires its exact old nullable digest. */
export function executionRecipe<T extends ExecutionRecipeId>(id: T, digest?: string | null): Extract<ExecutionRecipe, {profile_id:T}>;
export function executionRecipe(id: string, digest?: string | null): ExecutionRecipe;
export function executionRecipe(id: string, digest?: string | null): ExecutionRecipe {
  const row = executionRecipes.find(row => row.profile_id === id);
  if (!row || (digest !== undefined && row.profile_digest !== digest)) throw new Error("Unknown or tampered execution recipe");
  return row;
}
export type ExecutionRecipeQualification = {
  profile_id: string; recipe_digest: string;
  kind: "LEGACY_COMPATIBILITY_REFERENCE" | "CANDIDATE_NOT_QUALIFIED" | "PRODUCT_RUN_QUALIFIED";
  receipt_path: string | null; receipt_sha256: string | null;
};
export function executionRecipeQualification(id: string): ExecutionRecipeQualification {
  executionRecipe(id);
  return EXECUTION_RECIPE_TABLE.qualification_references.find(row => row.profile_id === id)!;
}
/** Existing preview exception, never inherited by another recipe/environment. */
export function executionRecipeBudgets(row: ExecutionRecipe, flags: RecipeFlags) {
  const override = row.preview_override;
  const enabled = override !== null && flags[override.flag] === "true";
  if (enabled && (flags.PORTAL_ENV !== undefined && flags.PORTAL_ENV !== override.required_environment
      || flags.AUTH_MODE !== undefined && flags.AUTH_MODE !== override.required_auth_mode)) throw new Error("Preview recipe budget is outside local/dev");
  return enabled ? {...row.budgets, cpu_seconds: override.cpu_seconds, wall_seconds: override.wall_seconds} : {...row.budgets};
}
export function executionRecipeTrialCount(row: ExecutionRecipe, flags: RecipeFlags) {
  executionRecipeBudgets(row, flags); // same environment guard as child/queue budget
  return row.preview_override !== null && flags[row.preview_override.flag] === "true"
    ? {min:row.preview_override.min_trials, max:row.preview_override.max_trials} : {...row.public_profile.trial_count};
}
export function executionRecipeResources(row: ExecutionRecipe, flags: RecipeFlags) {
  const b = executionRecipeBudgets(row, flags);
  return {memoryBytes:b.memory_bytes, cpuSeconds:b.cpu_seconds, scratchBytes:b.scratch_bytes, ioBytes:b.io_bytes};
}
/** Activation is separate from descriptor/qualification custody. */
export function executionRecipeActivationReason(row: ExecutionRecipe, flags: RecipeFlags,
  source: {engine_release_id:string; verified:boolean; context_qualified?:boolean}):
    "ENGINE_RELEASE_MISMATCH" | "SOURCE_RELEASE_UNVERIFIED" | "RUN_PRODUCER_OFF" | "PROFILE_FLAG_OFF" | "SOURCE_PROFILE_UNQUALIFIED" | "RECIPE_NOT_QUALIFIED" | null {
  const qualification = executionRecipeQualification(row.profile_id);
  if (source.engine_release_id !== row.descriptor.engine_release_id) return "ENGINE_RELEASE_MISMATCH";
  if (!source.verified) return "SOURCE_RELEASE_UNVERIFIED";
  for (const flag of row.feature_flags) if (flags[flag] !== "true")
    return flag === "FEATURE_RESEARCH_RUN_PRODUCER" ? "RUN_PRODUCER_OFF" : "PROFILE_FLAG_OFF";
  if (qualification.kind === "CANDIDATE_NOT_QUALIFIED" && !(flags.RESEARCH_RECIPE_QUALIFICATION_PROFILE_ID === row.profile_id
      && flags.PORTAL_ENV === "local" && flags.AUTH_MODE === "dev")) return "RECIPE_NOT_QUALIFIED";
  if (row.source_requirement === "VN_OBSERVED_EXACT_QUALIFICATION" && !source.context_qualified)
    return "SOURCE_PROFILE_UNQUALIFIED";
  return null;
}
/** Exact family selection; numerical topology/declared pins stay in named adapters. */
export function wfoExecutionRecipe(spec: {schema_version:string; optimization_schedule:string; optimization_mode?:string; execution_route?:string;
  data?:{timeframe:string};alpha_binding?:{alpha_version_id:string}|null}): Extract<ExecutionRecipe,{adapter_kind:"DELTA_WFO"}> | null {
  const matches = executionRecipes.filter((row): row is Extract<ExecutionRecipe,{adapter_kind:"DELTA_WFO"}> => row.adapter_kind === "DELTA_WFO"
    && (row.public_profile.requested_spec_versions as readonly string[]).includes(spec.schema_version)
    && row.public_profile.optimization_schedule === spec.optimization_schedule
    && row.public_profile.optimization_mode === (spec.optimization_mode ?? "mode_1_decay")
    && row.public_profile.execution_route === (spec.execution_route ?? "signal_notional")
    && row.public_profile.timeframe === (spec.data?.timeframe ?? "1h")
    && (row.source_requirement === "FULL03_IMMUTABLE_DELTA_BINDING"
      ? row.descriptor.alpha_binding_requirements.alpha_version_id === spec.alpha_binding?.alpha_version_id
      : !["av_delta_rsi_polynomial_alpha_1_0_1","av_delta_rsi_polynomial_alpha_1_0_2"].includes(spec.alpha_binding?.alpha_version_id ?? "")));
  if (matches.length > 1) throw new Error("Ambiguous WFO execution recipe");
  return matches[0] ?? null;
}
